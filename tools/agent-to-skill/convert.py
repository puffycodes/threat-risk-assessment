class ConvertError(Exception):
    pass


def parse_frontmatter(text, source):
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise ConvertError(f"{source}: no frontmatter")
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        raise ConvertError(f"{source}: frontmatter is not closed")
    fields = {}
    for line in lines[1:end]:
        if not line.strip():
            continue
        m = re.match(r"^([A-Za-z][\w-]*):\s?(.*)$", line)
        if not m:
            raise ConvertError(f"{source}: can't read frontmatter line {line!r} (only one-line fields are supported)")
        fields[m.group(1)] = m.group(2).strip()
    body = "\n".join(lines[end + 1:]).lstrip("\n")
    return fields, body


def yaml_value(value):
    if re.search(r":\s|\s#|^[\"'{&*!|>%@`]", value):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return value


def split_tools(value):
    return [t.strip() for t in value.split(",") if t.strip()]


def apply_exact(text, rules, source, table):
    for old, new in rules:
        count = text.count(old)
        if count != 1:
            first = old.split("\n")[0][:70]
            raise ConvertError(
                f"{source}: rewrite rule starting {first!r} matches {count} times, not once. "
                f"The source wording has changed; update {table} in tools/agent-to-skill/convert.py.")
        text = text.replace(old, new)
    return text


def bundled_path(doc_path):
    """Map a docs/ path to its place in the skill folder."""
    rel = doc_path[len("docs/"):]
    if rel.startswith("templates/"):
        return rel
    return "references/" + rel


LINK_RE = re.compile(r"\[([^\]\n]*)\]\(([^)\s]+)\)")


def is_local_link(target):
    return not re.match(r"[a-z][a-z0-9+.-]*:|#", target, re.I)


def fix_links(text, doc, doc_paths):
    """Point a copied file's relative links at the copies in the skill folder.

    A link to a file the skill also copies is rewritten to that copy's place.
    A link to anything else is dropped, keeping its text, because the file
    isn't in the skill folder.
    """
    here = posixpath.dirname(bundled_path(doc))

    def fix(m):
        label, target = m.groups()
        if not is_local_link(target):
            return m.group(0)
        path, sep, fragment = target.partition("#")
        linked = posixpath.normpath(posixpath.join(posixpath.dirname(doc), path))
        if linked not in doc_paths:
            return label
        return f"[{label}]({posixpath.relpath(bundled_path(linked), here or '.')}{sep}{fragment})"

    return LINK_RE.sub(fix, text)


def broken_links(text, base_dir, skill_dir):
    """Relative links in text that don't lead to a file in the skill folder."""
    broken = []
    for label, target in LINK_RE.findall(text):
        if not is_local_link(target):
            continue
        linked = (base_dir / target.partition("#")[0]).resolve()
        if not linked.is_file() or skill_dir.resolve() not in linked.parents:
            broken.append(target)
    return broken


def tool_phrases(tools, source):
    phrases = []
    for tool in tools:
        phrase = TOOL_PHRASES.get(tool)
        if phrase is None:
            raise ConvertError(f"{source}: no plain-language phrase for tool {tool!r}; add it to TOOL_PHRASES")
        if phrase not in phrases:
            phrases.append(phrase)
    return phrases


def compatibility(tools):
    """The specification's `compatibility` field: what the host must provide."""
